type SecondYear = 97 | 98 | 99 | 100;

interface ImageQuestionInput {
  year: SecondYear;
  number: number;
  chapterId: ChapterId;
  topic: string;
  stem: string;
  options?: [string, string, string, string];
  figure?: QuestionFigure | null;
  officialImageOnly?: boolean;
  answer: OptionId;
  height: number;
  summary: string;
  reasoning: string;
  optionReasons: [string, string, string, string];
  questionGroup?: BiologyQuestion["questionGroup"];
}

function officialFigure(
  year: SecondYear,
  filename: string,
  height: number,
  alt: string,
  width = 1080,
): QuestionFigure {
  return {
    src: `/questions/${year}/${filename}`,
    alt: `${year} 年第二次基測${alt}`,
    width,
    height,
  };
}

function imageQuestion(input: ImageQuestionInput): BiologyQuestion {
  return makeBasicQuestion({
    year: input.year,
    number: input.number,
    session: "第二次",
    chapterId: input.chapterId,
    topic: input.topic,
    stem: input.stem,
    options: input.options ?? [
      "請見官方題圖中的（A）選項",
      "請見官方題圖中的（B）選項",
      "請見官方題圖中的（C）選項",
      "請見官方題圖中的（D）選項",
    ],
    answer: input.answer,
    figure: input.figure === null
      ? undefined
      : input.figure ?? officialFigure(
        input.year,
        `second-q${String(input.number).padStart(2, "0")}-official.webp`,
        input.height,
        `第 ${input.number} 題完整官方題面`,
      ),
    officialImageOnly: input.officialImageOnly ?? true,
    questionGroup: input.questionGroup,
    summary: input.summary,
    reasoning: input.reasoning,
    optionReasons: input.optionReasons,
    shuffleSafe: false,
  });
}

