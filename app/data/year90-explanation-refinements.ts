export function validateYear90ExplanationQuality(
  questions: BiologyQuestion[],
): void {
  const year90 = questions.filter(
    (question) =>
      question.source.year === 90 &&
      question.source.exam === "國民中學學生基本學力測驗",
  );

  if (year90.length !== Object.keys(refinements).length) {
    throw new Error(
      `90 年逐題詳解不完整：題庫 ${year90.length} 題，詳解 ${Object.keys(refinements).length} 題`,
    );
  }

  year90.forEach((question) => {
    if (!refinements[question.id]) {
      throw new Error(`${question.id}: 缺少 90 年逐題詳解`);
    }

    const allText = [
      question.explanation.summary,
      question.explanation.reasoning,
      ...question.explanation.optionAnalysis.map((row) => row.reason),
    ].join("\n");

    forbiddenTemplateFragments.forEach((fragment) => {
      if (allText.includes(fragment)) {
        throw new Error(`${question.id}: 仍含錯誤或空泛的批次模板「${fragment}」`);
      }
    });

    if (question.explanation.optionAnalysis.some((row) => row.reason.length < 18)) {
      throw new Error(`${question.id}: 選項解析過短`);
    }

    const officialReason = question.explanation.optionAnalysis.find(
      (row) => row.optionId === question.officialAnswer,
    )?.reason;
    if (
      !officialReason ||
      (!officialReason.includes("正確") && !officialReason.includes("本題要找"))
    ) {
      throw new Error(`${question.id}: 官方答案的選項解析未明確標示判斷`);
    }
  });
}
