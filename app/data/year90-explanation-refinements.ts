export function refineYear90Explanations(
  questions: BiologyQuestion[],
): BiologyQuestion[] {
  return questions.map((question) => {
    const refinement = refinements[question.id];
    if (!refinement) return question;

    return {
      ...question,
      explanation: {
        ...question.explanation,
        summary: refinement.summary,
        reasoning: refinement.reasoning,
        optionAnalysis: question.options.map((option) => ({
          optionId: option.id,
          reason: refinement.optionReasons[option.id],
        })),
      },
    };
  });
}

